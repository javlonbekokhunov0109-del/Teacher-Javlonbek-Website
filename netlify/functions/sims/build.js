// Turns the page files in sims/src/*.html into sims/pages.js (a normal JS module), so Netlify's bundler
// always ships them inside the functions that need them. Run:  node netlify/functions/sims/build.js
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "src"), out = {};
fs.readdirSync(dir).filter((f) => f.endsWith(".html")).sort().forEach((f) => { out[f] = fs.readFileSync(path.join(dir, f), "utf8"); });
fs.writeFileSync(path.join(__dirname, "pages.js"), "// GENERATED by sims/build.js from sims/src/*.html - do not edit by hand\nmodule.exports = " + JSON.stringify(out) + ";\n");
console.log("pages.js:", Object.keys(out).length, "pages,", Math.round(fs.statSync(path.join(__dirname, "pages.js")).size / 1024), "KB");
