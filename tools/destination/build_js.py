import json, os
d = json.load(open("clean.json"))
META = {
 "A1": ("Destination A1", "Beginner \u00b7 Elementary", "Uzbek translations and example sentences by Zoir Akramov (@Zoir_Akramov). Word list from \u201cDestination A1\u201d by Malcolm Mann and Steve Taylore-Knowles."),
 "A2": ("Destination A2", "Elementary", "Uzbek translations and example sentences by Zoir Akramov (@Zoir_Akramov). Word list from \u201cDestination A2\u201d by Malcolm Mann and Steve Taylore-Knowles."),
 "B1": ("Destination B1", "Intermediate", "Uzbek translations from the Telegram channel @destination_b1_b2_c1. Word list from \u201cDestination B1\u201d by Malcolm Mann and Steve Taylore-Knowles."),
 "B2": ("Destination B2", "Upper-Intermediate", "Uzbek translations from the Telegram channel @destination_b1_b2_c1. Word list from \u201cDestination B2\u201d by Malcolm Mann and Steve Taylore-Knowles."),
}
os.makedirs("/home/claude/repo/js", exist_ok=True)
for b, units in d.items():
    secs = []
    for u in units:
        for i in u["items"]:
            if i["sec"] not in secs: secs.append(i["sec"])
    out = {"id": b.lower(), "name": META[b][0], "level": META[b][1], "credit": META[b][2], "secs": secs, "units": [
        {"n": u["n"], "t": u["title"], "c": [([i["en"], i["uz"], secs.index(i["sec"])] + ([i["ex"], i["exuz"]] if i.get("ex") else [])) for i in u["items"]]} for u in units]}
    js = "/* Destination %s vocabulary: %d cards in %d units. Generated by tools/ (do not edit by hand). card = [english, uzbek, section index, example, example in Uzbek] */\nwindow.DEST=window.DEST||{};window.DEST.%s=%s;\n" % (b, sum(len(u["c"]) for u in out["units"]), len(units), b.lower(), json.dumps(out, ensure_ascii=False, separators=(",", ":")))
    open(f"/home/claude/repo/js/dest-{b.lower()}.js", "w", encoding="utf-8").write(js)
    print(f"{b}: {sum(len(u['c']) for u in out['units'])} cards, {len(js)//1024} KB, sections: {secs}")
